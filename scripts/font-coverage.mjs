// The browser checks entries against the PDF font's characters without downloading the 1 MB font, so the
// character list ships separately as ranges. scripts/build-pdf-vendor.mjs writes it and npm run check compares it.
export const COVERAGE_PATH = 'js/pdf-font-coverage.js';

export function coverageRanges(codePoints) {
  const sorted = [...new Set(codePoints)].sort((a, b) => a - b);
  const ranges = [];
  for (const point of sorted) {
    const last = ranges.at(-1);
    if (last && point === last[1] + 1) last[1] = point;
    else ranges.push([point, point]);
  }
  return ranges;
}

export function coverageModule(codePoints) {
  return '// Generated by scripts/build-pdf-vendor.mjs from the embedded PDF font. Do not edit.\n'
    + '// Inclusive [first, last] code point ranges the permit PDF can print.\n'
    + `export const PRINTABLE_RANGES = ${JSON.stringify(coverageRanges(codePoints))};\n`;
}
