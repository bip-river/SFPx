import { build } from 'esbuild';
import { readFile, writeFile, copyFile, mkdir } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { create } from 'fontkit';
const require = createRequire(import.meta.url);
await mkdir('vendor', { recursive: true });
await build({
  stdin: { contents: "import pdfMake from 'pdfmake/build/pdfmake.js'; export default pdfMake;", resolveDir: process.cwd() },
  outfile: 'vendor/pdfmake.js', bundle: true, format: 'esm', platform: 'browser', minify: true, legalComments: 'linked'
});
const font = await readFile(require.resolve('dejavu-fonts-ttf/ttf/DejaVuSans.ttf'));
const coverage = create(font).characterSet;
await writeFile('vendor/permit-font.js', `// Generated by scripts/build-pdf-vendor.mjs; see DejaVu-LICENSE.txt.\nexport const codePoints = ${JSON.stringify(coverage)};\nexport default { 'DejaVuSans.ttf': '${font.toString('base64')}' };\n`);
await copyFile(require.resolve('dejavu-fonts-ttf/LICENSE'), 'vendor/DejaVu-LICENSE.txt');
await copyFile(require.resolve('pdfmake/LICENSE'), 'vendor/pdfmake-LICENSE.txt');
console.log('Generated self-hosted PDF engine and embedded font.');
